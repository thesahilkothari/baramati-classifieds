export function normalizeLanguage(language) {
  return language === "mr" ? "mr" : "en";
}

export function t(language, key) {
  const normalizedLanguage = normalizeLanguage(language);

  return (
    UI_TEXT[normalizedLanguage]?.[key] ||
    UI_TEXT[DEFAULT_LANGUAGE]?.[key] ||
    key
  );
}

export function getLanguageFromCookieStore(cookieStore) {
  const value = cookieStore?.get?.(LANGUAGE_COOKIE_NAME)?.value;

  return normalizeLanguage(value);
}

export function getHtmlLang(language) {
  return normalizeLanguage(language) === "mr" ? "mr-IN" : "en-IN";
}
